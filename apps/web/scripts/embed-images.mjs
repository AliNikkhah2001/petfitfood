/**
 * Re-embeds photography from public/images into src/lib/images.data.ts.
 *
 * Photos are inlined as data URIs rather than served from /public because
 * binary assets have repeatedly been stripped from this project, which is
 * what caused the "pictures missing" regressions. Inlining keeps them in
 * the source tree and the built bundle.
 *
 * Usage:  node scripts/embed-images.mjs
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const DIR = "public/images";
const MIME = { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp" };

const PHOTO_KEYS = {
  "hero.jpg": "hero", "dog.jpg": "dog", "cat.jpg": "cat",
  "treats.jpg": "treats", "nature.jpg": "nature", "bond.jpg": "bond",
};

const ing = (f) => f.startsWith("ing-") && f.endsWith(".webp");
const ingKey = (f) => f.slice(4, -5); // strip "ing-" and ".webp"

const files = readdirSync(DIR).filter((f) => MIME[f.slice(f.lastIndexOf("."))]);
const uri = (f) => {
  const buf = readFileSync(join(DIR, f));
  const type = MIME[f.slice(f.lastIndexOf("."))];
  return `data:${type};base64,${buf.toString("base64")}`;
};

const photos = Object.entries(PHOTO_KEYS)
  .filter(([f]) => files.includes(f))
  .map(([f, key]) => `  ${key}: ${JSON.stringify(uri(f))},`)
  .join("\n");

const ingredients = files
  .filter(ing)
  .sort()
  .map((f) => `  ${ingKey(f)}: ${JSON.stringify(uri(f))},`)
  .join("\n");

const out = `/* AUTO-GENERATED by scripts/embed-images.mjs — do not edit by hand.
 *
 * Photography is inlined as data URIs so the imagery lives in the source
 * tree and the built bundle; it can never 404 or be dropped from a deploy.
 * Replace a file in public/images, then re-run the script.
 */

export const PHOTOS = {
${photos}
} as const;

export const INGREDIENTS = {
${ingredients}
} as const;
`;

writeFileSync("src/lib/images.data.ts", out);
const bytes = files.reduce((n, f) => n + statSync(join(DIR, f)).size, 0);
console.log(`embedded ${files.length} images (${(bytes / 1024).toFixed(0)} KB) -> src/lib/images.data.ts`);
